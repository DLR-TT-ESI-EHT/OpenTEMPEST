class Html2Md(HTMLParser):
    BLOCK = {"p", "div", "ul", "ol", "pre", "h1", "h2", "h3", "h4", "h5", "h6", "dl", "table", "blockquote"}

    def __init__(self, link_fn, heading_base=3):
        super().__init__(convert_charrefs=True)
        self.out, self.link_fn, self.base = [], link_fn, heading_base
        self.lists, self.pre, self.href, self.table, self.skip = [], False, None, None, 0
        self.link_text = None

    def w(self, s):
        if self.table is not None:
            self.table.append(s)
        elif self.link_text is not None:
            self.link_text.append(s)
        else:
            self.out.append(s)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if self.table is not None:
            self.table.append(self.table_tag(tag, attrs))
            if tag == "table":
                self.skip += 1
            return
        if tag == "table":
            self.table = [self.table_tag(tag, attrs)]
            self.skip = 1
        elif tag in ("html", "body", "head", "span", "font", "c"):
            pass
        elif tag == "p" or tag == "div":
            self.w("\n\n")
        elif tag == "br":
            self.w("  \n" if not self.pre else "\n")
        elif re.match(r"h[1-6]$", tag):
            level = min(6, max(self.base, int(tag[1]) - 1))
            self.w("\n\n" + "#" * level + " ")
        elif tag in ("ul", "ol"):
            self.lists.append([tag, 0])
            self.w("\n")
        elif tag == "li":
            ind = "  " * (len(self.lists) - 1)
            if self.lists and self.lists[-1][0] == "ol":
                self.lists[-1][1] += 1
                self.w("\n%s%d. " % (ind, self.lists[-1][1]))
            else:
                self.w("\n%s- " % ind)
        elif tag == "dt":
            self.w("\n\n**")
        elif tag == "dd":
            self.w("\n: ")
        elif tag == "pre":
            self.pre = True
            self.w("\n\n```\n")
        elif tag in ("code", "tt") and not self.pre:
            self.w("`")
        elif tag in ("b", "strong"):
            self.w("**")
        elif tag in ("i", "em"):
            self.w("*")
        elif tag in ("sub", "sup"):
            self.w("<%s>" % tag)
        elif tag == "a":
            self.href = a.get("href")
            self.link_text = []
        elif tag == "img":
            src = a.get("src", "")
            if not src.startswith("modelica://"):
                self.w("![%s](%s)" % (a.get("alt", ""), src))

    def table_tag(self, tag, attrs):
        """Start tag inside a raw HTML table, with modelica:// links turned into page links."""
        if tag == "a":
            href = dict(attrs).get("href", "")
            target = self.link_fn(href) if href else None
            return '<a href="%s">' % html.escape(target, quote=True) if target else "<a>"
        return self.get_starttag_text()

    def handle_endtag(self, tag):
        if self.table is not None:
            self.table.append("</%s>" % tag)
            if tag == "table":
                self.skip -= 1
                if self.skip == 0:
                    self.out.append("\n\n" + "".join(self.table) + "\n\n")
                    self.table = None
            return
        if tag in ("p", "div"):
            self.w("\n\n")
        elif re.match(r"h[1-6]$", tag):
            self.w("\n\n")
        elif tag in ("ul", "ol"):
            if self.lists:
                self.lists.pop()
            self.w("\n\n")
        elif tag == "dt":
            self.w("**")
        elif tag == "pre":
            self.pre = False
            self.w("\n```\n\n")
        elif tag in ("code", "tt") and not self.pre:
            self.w("`")
        elif tag in ("b", "strong"):
            self.w("**")
        elif tag in ("i", "em"):
            self.w("*")
        elif tag in ("sub", "sup"):
            self.w("</%s>" % tag)
        elif tag == "a":
            text = "".join(self.link_text or []).strip()
            self.link_text = None
            target = self.link_fn(self.href) if self.href else None
            if target:
                self.w("[%s](%s)" % (text or self.href, target))
            elif self.href and self.href.startswith("modelica://"):
                self.w("`%s`" % (text or self.href[11:]))
            else:
                self.w(text)
            self.href = None

    def handle_data(self, data):
        if self.table is not None:
            self.table.append(html.escape(data, quote=False))
            return
        if self.pre:
            self.w(data)
        else:
            self.w(re.sub(r"\s+", " ", data))

    def result(self):
        s = "".join(self.out)
        lines = [l.rstrip() if not l.endswith("  ") else l for l in s.split("\n")]
        s = "\n".join(lines)
        s = re.sub(r"\n[ \t]+(?=[^\s-])", "\n", s) if False else s
        s = re.sub(r"(?m)^ (?=\S)", "", s)
        s = re.sub(r"\n{3,}", "\n\n", s)
        return s.strip()


def html_to_md(src_html, link_fn):
    p = Html2Md(link_fn)
    p.feed(src_html)
    p.close()
    return p.result()


