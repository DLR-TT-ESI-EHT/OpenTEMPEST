#!/usr/bin/env python3
"""Build the Markdown library reference in docs/library-reference.

The reference combines two sources:

* The Dymola documentation export (File > Export > Documentation, Markdown),
  which provides the parameter, connector, input and output tables including
  inherited elements.
* The Modelica source in OpenTEMPEST/, which provides the class kind, the
  description string and the Documentation(info=...) text. The source always
  wins, so docstring edits show up without a new Dymola export.

Usage (from the repository root):

    # after a fresh Dymola export into docs/library-reference
    python docs/tools/build_reference.py --import-export

    # rebuild from the stored export data, e.g. after editing docstrings
    python docs/tools/build_reference.py

--import-export parses the raw Dymola Markdown files, stores the tables in
docs/library-reference/_export.json and then writes the tidy pages. Without it,
the tables are read from _export.json. Only the Python standard library is used.
"""
import argparse
import bisect
import html
import json
import os
import re
import sys
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "OpenTEMPEST")
OUT = os.path.join(REPO, "docs", "library-reference")
EXPORT_JSON = "_export.json"
MARKER = "<!-- Generated by docs/tools/build_reference.py"
LIB = "OpenTEMPEST"

KINDS = ("model", "block", "function", "package", "record", "connector", "type", "class")
SECTION_TITLES = ("Information", "Parameters", "Connectors", "Inputs", "Outputs", "Contents", "Package Content")


# ----------------------------------------------------------------------------
# Modelica source
# ----------------------------------------------------------------------------

def read_text(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8-sig", errors="replace").replace("\r\n", "\n")


def unescape_mo(s):
    return s.replace('\\"', '"').replace("\\\\", "\\")


HEADER_RE = re.compile(
    r"^[ \t]*(?:(?:partial|encapsulated|operator|expandable|final|replaceable)\s+)*"
    r"(" + "|".join(KINDS) + r")\s+(\w+)\b(.*)$", re.M)


def string_at(s, i):
    """Return (content, end) of the Modelica string starting at s[i] == '"'."""
    j = i + 1
    while j < len(s):
        if s[j] == "\\":
            j += 2
            continue
        if s[j] == '"':
            return s[i + 1:j], j + 1
        j += 1
    return s[i + 1:], len(s)


def parse_source():
    """Return {full name: info dict} for all classes in the library."""
    classes = {}
    for dirpath, _, files in os.walk(SRC):
        for fn in files:
            if not fn.endswith(".mo"):
                continue
            path = os.path.join(dirpath, fn)
            s = read_text(path)
            m = re.match(r"\s*within\s+([\w.]*)\s*;", s)
            within = m.group(1) if m else ""
            stack = []  # (name, full)
            pos = 0
            # walk class headers and end statements in order
            token_re = re.compile(HEADER_RE.pattern + r"|^[ \t]*end\s+(\w+)\s*;", re.M)
            spans = literal_spans(s)
            for tm in token_re.finditer(s):
                if in_spans(spans, tm.start(2) if tm.group(2) else tm.start(4)):
                    continue
                if tm.group(4):  # end Name;
                    if stack and stack[-1][0] == tm.group(4):
                        full = stack.pop()[1]
                        classes[full]["_end"] = tm.start()
                    continue
                kind, name, rest = tm.group(1), tm.group(2), tm.group(3)
                # skip component declarations like "replaceable model X = Y" inside classes
                parent = stack[-1][1] if stack else within
                is_short = bool(re.match(r"\s*=", rest))
                if is_short and stack and kind in ("model", "package", "function", "record", "block"):
                    # replaceable model Electrochem = ... is an element, not a documented class
                    continue
                full = (parent + "." if parent else "") + name
                info = {"kind": kind, "name": name, "file": os.path.relpath(path, SRC).replace(os.sep, "/"),
                        "desc": "", "info": "", "enum": [], "_start": tm.start(), "partial": "partial" in s[tm.start():tm.start(2)]}
                after = s[tm.end(2):]
                if is_short:
                    # short definition, description is the last string before ';'
                    semi = find_semicolon(s, tm.end(2))
                    body = s[tm.end(2):semi]
                    dm = re.search(r'"((?:[^"\\]|\\.)*)"\s*$', body.rstrip())
                    if dm:
                        info["desc"] = unescape_mo(dm.group(1))
                    em = re.search(r"enumeration\s*\((.*)\)", body, re.S)
                    if em:
                        for lit in re.finditer(r'(\w+)\s*(?:"((?:[^"\\]|\\.)*)")?\s*(?:,|$)', em.group(1)):
                            info["enum"].append((lit.group(1), unescape_mo(lit.group(2) or "")))
                    classes[full] = info
                    continue
                dm = re.match(r'\s*"', after)
                if dm:
                    desc, _ = string_at(s, tm.end(2) + dm.end() - 1)
                    info["desc"] = unescape_mo(desc)
                classes[full] = info
                stack.append((name, full))
            # Documentation info: assign to the innermost class containing it
            for im in re.finditer(r"\binfo\s*=\s*\"", s):
                content, _ = string_at(s, im.end() - 1)
                owner = None
                for full, c in classes.items():
                    if c["file"] == os.path.relpath(path, SRC).replace(os.sep, "/") and \
                            c["_start"] < im.start() < c.get("_end", len(s)):
                        if owner is None or c["_start"] > classes[owner]["_start"]:
                            owner = full
                if owner:
                    classes[owner]["info"] = unescape_mo(content)
            # element descriptions declared in each class (used to fill empty table cells)
    for full, c in classes.items():
        c["elements"] = {}
    for full, c in classes.items():
        path = os.path.join(SRC, c["file"])
        s = read_text(path)
        body = s[c["_start"]:c.get("_end", len(s))]
        for em in ELEMENT_RE.finditer(body):
            name, typ, desc = em.group(2), em.group(1), em.group(3)
            if name in c["elements"]:
                continue
            c["elements"][name] = (typ, unescape_mo(desc) if desc else "")
        for gm in re.finditer(r'\b(?:tab|group)\s*=\s*"([^"]+)"', body):
            GROUPS.add(gm.group(1))
    return classes


def literal_spans(s):
    """Start/end offsets of strings and comments, so headers inside them are ignored."""
    spans, i, n = [], 0, len(s)
    while i < n:
        if s[i] == '"':
            _, j = string_at(s, i)
            spans.append((i, j))
            i = j
        elif s.startswith("//", i):
            j = s.find("\n", i)
            j = n if j < 0 else j
            spans.append((i, j))
            i = j
        elif s.startswith("/*", i):
            j = s.find("*/", i)
            j = n if j < 0 else j + 2
            spans.append((i, j))
            i = j
        else:
            i += 1
    return spans


def in_spans(spans, pos):
    k = bisect.bisect_right(spans, (pos, float("inf"))) - 1
    return k >= 0 and spans[k][0] <= pos < spans[k][1]


GROUPS = set()
ELEMENT_RE = re.compile(
    r"^[ \t]*(?:(?:parameter|constant|input|output|flow|stream|inner|outer|final|replaceable|discrete)\s+)*"
    r"((?!end\b|equation\b|algorithm\b|annotation\b|extends\b|import\b|connect\b|initial\b|protected\b|public\b)[A-Za-z][\w.]*)"
    r"(?:\s*\[[^\]]*\])?\s+(\w+)\b(?:(?!annotation)[^;\"=])*(?:=(?:(?!annotation)[^;\"])*)?"
    r"(?:\"((?:[^\"\\]|\\.)*)\")?", re.M)


def find_semicolon(s, i):
    depth, in_str = 0, False
    while i < len(s):
        ch = s[i]
        if in_str:
            if ch == "\\":
                i += 1
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == ";" and depth == 0:
            return i
        i += 1
    return i


