def github_slug(text):
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


class Site:
    def __init__(self, src, export):
        self.src, self.export = src, export
        # packages that get their own page
        self.pages = {full for full, c in src.items() if c["kind"] == "package" and is_page(full, src, export)}
        self.pages.add(LIB)
        self.location = {}  # full name -> (page file, anchor or "")
        for full in src:
            if full in self.pages:
                self.location[full] = (page_file(full), "")
            else:
                parent = full.rsplit(".", 1)[0]
                while parent and parent not in self.pages:
                    parent = parent.rsplit(".", 1)[0]
                self.location[full] = (page_file(parent or LIB), github_slug(full.rsplit(".", 1)[1]))
        # Dymola anchors -> class
        self.dymola = {}
        for full, (page, _) in self.location.items():
            short = full.rsplit(".", 1)[-1]
            self.dymola[(page, norm(full))] = full
            self.dymola.setdefault((page, norm(short)), full)

    def link(self, full, from_page):
        if full not in self.location:
            return None
        page, anchor = self.location[full]
        if page == from_page:
            return "#" + anchor if anchor else "#" + github_slug(full)
        return page + ("#" + anchor if anchor else "")

    def fix_md_links(self, text, from_page):
        def repl(m):
            label, target = m.group(1), m.group(2)
            if target.startswith(("http://", "https://", "mailto:")) or not ".md" in target:
                return m.group(0)
            page, _, anchor = target.partition("#")
            full = self.dymola.get((page, norm(anchor))) if anchor else None
            if full is None and anchor:
                # Dymola sometimes points to the package page anchor
                for f2, (p2, a2) in self.location.items():
                    if p2 == page and a2 == "" and norm(f2) == norm(anchor):
                        full = f2
                        break
            if full is None:
                pkg = page[:-3].replace("_", ".")
                full = pkg if pkg in self.location else None
            new = self.link(full, from_page) if full else target
            return "[%s](%s)" % (label, new)
        return re.sub(r"(?<!!)\[([^\]]*)\]\(([^)\s]*)\)", repl, text)

    def modelica_link(self, from_page):
        def fn(href):
            if href and href.startswith("modelica://"):
                name = href[len("modelica://"):].split("#")[0]
                return self.link(name, from_page)
            return href
        return fn


def is_page(full, src, export):
    """A package gets its own page if it is a directory package or Dymola exported a page for it."""
    c = src[full]
    if c["file"] == "package.mo" or (c["file"].endswith("/package.mo") and full.endswith("." + c["file"].split("/")[-2])):
        return True
    return export.get(full, {}).get("page") == page_file(full)


def md_escape_cell(s):
    return s.replace("|", "\\|")


def clean_name(cell):
    name = cell.replace("\\[", "[").replace("\\]", "]").replace("\\_", "_").strip()
    return name


def render_table(rows, kind, owner, site, page):
    """Render a Parameters / Connectors / Inputs / Outputs / Contents table."""
    out, pending_group = [], None
    for name, desc in rows:
        raw_name = clean_name(name)
        desc = desc.replace("\xa0", " ").strip()
        m = re.match(r"^(replaceable\s+)?(model|package|function|record|block)\s+(\w+)$", raw_name)
        if m and kind == "Connectors":
            continue
        if not m and not desc and (raw_name in GROUPS or " " in raw_name or raw_name == "Inherited"):
            pending_group = raw_name
            continue
        ident = re.match(r"(\w+)", raw_name)
        unit = ""
        um = re.search(r"\s*\\\[([^\]]*)\\\]\s*$", desc)
        if um:
            unit, desc = um.group(1).replace("\\", ""), desc[:um.start()].strip()
        if unit == "1":
            unit = ""
        if not desc and (m or ident):
            typ, d = owner_element(site, owner, m.group(3) if m else ident.group(1))
            desc = md_escape_cell(d) if d else ("`%s`" % typ if typ and kind == "Connectors" else "")
        desc = site.fix_md_links(desc, page)
        if pending_group:
            out.append("| **%s** | | |" % pending_group)
            pending_group = None
        if m:
            label = "`%s`" % m.group(3)
            desc = ("*replaceable %s*" % m.group(2)) + (": " + desc if desc else "")
        else:
            label = "`%s`" % md_escape_cell(raw_name)
        out.append("| %s | %s | %s |" % (label, desc, ("`%s`" % unit) if unit else ""))
    if not out:
        return ""
    return "| Name | Description | Unit |\n|---|---|---|\n" + "\n".join(out)


def owner_element(site, owner, name):
    """(type, description) of element `name` declared in `owner` or one of its base classes."""
    seen, todo, found_type = set(), [owner], ""
    while todo:
        full = todo.pop(0)
        if full in seen or full not in site.src:
            continue
        seen.add(full)
        el = site.src[full]["elements"].get(name)
        if el:
            if el[1]:
                return el
            found_type = found_type or el[0]
        for ext in site.export.get(full, {}).get("extends", []):
            for em in re.finditer(r"\[(" + LIB + r"[\w.]*)\]", ext):
                todo.append(em.group(1))
    return found_type, ""


def breadcrumb(full, site):
    parts = full.split(".")
    crumbs = []
    for i in range(1, len(parts)):
        p = ".".join(parts[:i])
        crumbs.append("[%s](%s)" % (parts[i - 1], page_file(p)))
    crumbs.append("**%s**" % parts[-1])
    return "[Library reference](README.md) › " + " › ".join(crumbs)


def class_block(full, site, page, level):
    c = site.src.get(full, {})
    e = site.export.get(full, {})
    short = full.rsplit(".", 1)[-1]
    lines = []
    if level == 2:
        lines.append("## %s" % short)
        lines.append("")
    icon = icon_file(full, "I")
    kind = ("partial " if c.get("partial") else "") + c.get("kind", "")
    if icon:
        lines.append('<img src="%s" alt="" width="60" align="right">' % icon)
        lines.append("")
    lines.append("`%s %s`" % (kind.strip(), full) if kind else "`%s`" % full)
    lines.append("")
    desc = c.get("desc") or plain(e.get("desc_md", ""))
    if desc and level == 2:
        lines.append("*%s*" % md_inline(desc))
        lines.append("")
    info = ""
    if c.get("info"):
        info = html_to_md(c["info"], site.modelica_link(page))
    elif e.get("info_md"):
        info = demote(site.fix_md_links(e["info_md"], page))
    if info:
        lines.append(info)
        lines.append("")
    if c.get("enum"):
        lines.append("| Literal | Description |\n|---|---|")
        for lit, d in c["enum"]:
            lines.append("| `%s` | %s |" % (lit, md_escape_cell(d)))
        lines.append("")
    for ext in e.get("extends", []):
        lines.append(site.fix_md_links(ext, page))
        lines.append("")
    for title in ("Parameters", "Connectors", "Inputs", "Outputs", "Contents"):
        rows = e.get("tables", {}).get(title)
        if not rows:
            continue
        table = render_table(rows, title, full, site, page)
        if table:
            lines.append("**%s**" % title)
            lines.append("")
            lines.append(table)
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def plain(md):
    return re.sub(r"\s+", " ", md).strip()


def md_inline(s):
    return s.replace("*", "\\*").replace("_", "\\_")


def demote(md):
    md = re.sub(r"(?m)^## .*\n?", "", md, count=1)
    return re.sub(r"(?m)^(#{1,5}) ", lambda m: "#" * max(3, len(m.group(1)) + 1) + " ", md).strip()


ICONS = set()


def icon_file(full, suffix):
    name = full + suffix + ".png"
    return name if name in ICONS else ""


def children(full, site):
    pref = full + "."
    kids = [k for k in site.src if k.startswith(pref) and "." not in k[len(pref):]]
    order = package_order(full, site)
    if order:
        kids.sort(key=lambda k: (order.index(k.rsplit(".", 1)[1]) if k.rsplit(".", 1)[1] in order else 999, k.lower()))
    else:
        # nested classes: keep the order of the source file
        kids.sort(key=lambda k: (site.src[k]["file"], site.src[k]["_start"]))
    return kids


def package_order(full, site):
    c = site.src.get(full)
    if not c:
        return []
    po = os.path.join(SRC, os.path.dirname(c["file"]), "package.order")
    d = os.path.dirname(c["file"])
    owns_dir = full == LIB if d == "" else full.endswith("." + os.path.basename(d))
    if c["file"].endswith("package.mo") and owns_dir and os.path.exists(po):
        return [l.strip() for l in read_text(po).splitlines() if l.strip()]
    return []


def render_page(full, site):
    page = page_file(full)
    c = site.src[full]
    out = [MARKER + ". Do not edit: change the Modelica source and re-run the script. -->", "",
           breadcrumb(full, site), "", "# %s" % full, ""]
    if c.get("desc"):
        out += ["*%s*" % md_inline(c["desc"]), ""]
    if c.get("info"):
        out += [html_to_md(c["info"], site.modelica_link(page)), ""]
    kids = children(full, site)
    if kids:
        out += ["| | Class | Kind | Description |", "|---|---|---|---|"]
        for k in kids:
            kc = site.src[k]
            icon = icon_file(k, "S")
            out.append("| %s | [%s](%s) | %s | %s |" % (
                ("![](%s)" % icon) if icon else "", k.rsplit(".", 1)[1], site.link(k, page),
                kc["kind"], md_escape_cell(kc.get("desc", ""))))
        out.append("")
    # package level tables (e.g. media)
    e = site.export.get(full, {})
    for ext in e.get("extends", []):
        out += [site.fix_md_links(ext, page), ""]
    inherited = inherited_rows(e)
    if inherited:
        out += ["<details><summary>Inherited content (%d entries)</summary>" % len(inherited), "",
                "| Name | Description |", "|---|---|"]
        for n, d in inherited:
            n = re.sub(r"!\[[^\]]*\]\([^)]*\)\s*", "", n)
            out.append("| %s | %s |" % (site.fix_md_links(n, page), d))
        out += ["", "</details>", ""]
    for title in ("Parameters", "Connectors", "Contents"):
        rows = e.get("tables", {}).get(title)
        if rows:
            t = render_table(rows, title, full, site, page)
            if t:
                out += ["**%s**" % title, "", t, ""]
    # classes documented on this page
    for k in kids:
        if k in site.pages:
            continue
        out += ["---", "", class_block(k, site, page, 2)]
        for kk in children(k, site):
            if kk not in site.pages:
                out += ["### %s" % kk.rsplit(".", 1)[1], "", class_block(kk, site, page, 3)]
        out += ["[Back to top](#%s)" % github_slug(full), ""]
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"
    check_anchors(text, page, full, kids, site)
    return text


def inherited_rows(e):
    rows = e.get("tables", {}).get("Package Content", [])
    out, on = [], False
    for n, d in rows:
        if n.strip() == "Inherited":
            on = True
            continue
        if on:
            out.append((n, d.replace("\xa0", " ")))
    return out


def check_anchors(text, page, full, kids, site):
    seen, slugs = {}, []
    for m in re.finditer(r"(?m)^#{1,6} (.+)$", text):
        s = github_slug(m.group(1))
        n = seen.get(s, 0)
        slugs.append(s if n == 0 else "%s-%d" % (s, n))
        seen[s] = n + 1
    for k in kids:
        if k in site.pages:
            continue
        a = site.location[k][1]
        if a not in slugs:
            print("warning: anchor #%s for %s not unique on %s" % (a, k, page))


def render_index(site):
    out = [MARKER + ". Do not edit: change the Modelica source and re-run the script. -->", "",
           "# OpenTEMPEST library reference", "",
           "Reference pages for every package, model, block and function in OpenTEMPEST. "
           "Each page lists the classes of one package with their description, parameters and connectors.", "",
           "The pages are generated from the Modelica source and the Dymola documentation export by "
           "[`docs/tools/build_reference.py`](../tools/build_reference.py). "
           "See [Writing documentation](../DocumentationStyle.md) for how to document a model.", "",
           "[Back to the documentation index](../../README.md#documentation-index)", ""]

    def walk(full, depth):
        for k in children(full, site):
            kc = site.src[k]
            if k in site.pages:
                out.append("%s- [**%s**](%s) — %s" % ("  " * depth, k.rsplit(".", 1)[1], page_file(k), kc.get("desc", "")))
                walk(k, depth + 1)
            elif depth <= 2 and kc["kind"] != "package":
                pass
    out.append("- [**OpenTEMPEST**](OpenTEMPEST.md) — %s" % site.src[LIB].get("desc", ""))
    walk(LIB, 1)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--import-export", action="store_true", help="parse a fresh Dymola export in docs/library-reference")
    args = ap.parse_args()

    src = parse_source()
    store = os.path.join(OUT, EXPORT_JSON)
    if args.import_export:
        export = parse_export(OUT)
        with open(store, "w", encoding="utf-8") as f:
            json.dump(export, f, indent=1, sort_keys=True, ensure_ascii=False)
    else:
        if not os.path.exists(store):
            sys.exit("No %s found. Run with --import-export after a Dymola export." % EXPORT_JSON)
        with open(store, encoding="utf-8") as f:
            export = json.load(f)
    ICONS.update(f for f in os.listdir(OUT) if f.endswith(".png"))
    site = Site(src, export)
    written = set()
    for full in sorted(site.pages):
        if full not in src:
            continue
        text = render_page(full, site)
        fn = page_file(full)
        with open(os.path.join(OUT, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.add(fn)
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(render_index(site))
    stale = [f for f in os.listdir(OUT) if f.endswith(".md") and f.startswith(LIB) and f not in written]
    for f in stale:
        print("note: %s does not belong to a package any more" % f)
    print("wrote %d pages to %s" % (len(written) + 1, os.path.relpath(OUT, REPO)))


if __name__ == "__main__":
    main()
