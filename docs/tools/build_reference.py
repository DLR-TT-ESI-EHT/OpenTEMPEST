def page_file(full):
    return full.replace(".", "_") + ".md"


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def parse_export(folder):
    """Parse raw Dymola Markdown export files into {full name: section data}."""
    data = {}
    for fn in sorted(os.listdir(folder)):
        if not (fn.startswith(LIB) and fn.endswith(".md")):
            continue
        text = read_text(os.path.join(folder, fn))
        if text.startswith(MARKER):
            sys.exit("%s is already a generated page. Re-export from Dymola before using --import-export." % fn)
        text = re.sub(r"\n\[Automatically generated\]\([^)]*\)[^\n]*", "\n", text)
        # class sections start with a linked heading; "## Title" lines inside
        # the information text are not section starts
        parts = re.split(r"(?m)^(?=## (?:!?\[|" + LIB + r"\s*$))", text)
        for part in parts:
            if not part.startswith("## "):
                continue
            head, _, body = part.partition("\n")
            full = heading_full_name(head)
            if not full:
                continue
            data[full] = parse_section(body)
            data[full]["page"] = fn
    return data


def heading_full_name(head):
    # "## ![Full](icon) [Parent](link).Name"  or  "## [Parent](link).Name"  or "## OpenTEMPEST"
    m = re.match(r"##\s+!\[([\w.]+)\]\(([^)]*)\)", head)
    icon = m.group(2) if m else ""
    m2 = re.search(r"\[([\w.]+)\]\([^)]*\)\.(\w+)\s*$", head)
    if m2:
        return m2.group(1) + "." + m2.group(2)
    m3 = re.match(r"##\s+([\w.]+)\s*$", head)
    if m3:
        return m3.group(1)
    if m:
        return m.group(1)
    return None


def parse_section(body):
    out = {"icon": "", "tables": {}, "extends": [], "info_md": "", "desc_md": ""}
    chunks = re.split(r"(?m)^### (" + "|".join(SECTION_TITLES) + r")\s*$", body)
    out["desc_md"] = chunks[0].strip()
    for title, content in zip(chunks[1::2], chunks[2::2]):
        if title == "Information":
            lines = []
            for line in content.strip().splitlines():
                if line.startswith("Extends from "):
                    out["extends"].append(line.strip())
                else:
                    lines.append(line)
            out["info_md"] = "\n".join(lines).strip()
        else:
            out["tables"][title] = parse_table(content)
    return out


def parse_table(content):
    rows = []
    for line in content.splitlines():
        line = line.strip()
        if not line.startswith("|") or re.match(r"^\|[\s\-|:]+\|$", line):
            continue
        cells = [c.strip() for c in split_row(line)]
        if len(cells) < 2 or (cells[0] == "Name" and cells[1] == "Description"):
            continue
        rows.append([cells[0], cells[1]])
    return rows


def split_row(line):
    cells, cur, depth, i = [], "", 0, 1
    while i < len(line):
        ch = line[i]
        if ch == "\\" and i + 1 < len(line):
            cur += line[i:i + 2]
            i += 2
            continue
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(0, depth - 1)
        if ch == "|" and depth == 0:
            cells.append(cur)
            cur = ""
        else:
            cur += ch
        i += 1
    return cells


